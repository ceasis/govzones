#!/usr/bin/env node
/**
 * Builds the directory seed migrations from the JSON seed batches:
 *   data/ph/directory.json → migrations/directory/0002_seed_ph.sql          (geography, agencies, LGUs)
 *   data/ph/offices.json   → migrations/directory/0003_seed_ph_offices.sql  (offices throughout the country)
 *
 * - Stable UUIDv5 entity IDs derived from each seed key (re-running never changes IDs).
 * - All seed listings are published as "pending source verification" (verified_at NULL).
 * - Curator review notes from the seed file are kept in the directory audit trail.
 * - Later batches may reference parents and places from earlier ones; slugs stay unique across all.
 *   A batch is a separate migration so databases that already carry the earlier ones only apply the
 *   new rows. Never edit a batch that has been applied to a deployed database: add a new one.
 *
 * Usage: node scripts/build-directory-seed.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { sha1 } from "@noble/hashes/legacy.js";
import { normalizeText, slugify } from "../shared/directory.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// Fixed namespace for GovZones seed identifiers.
const NAMESPACE = "6f1c2a8e-4b7d-5e3f-9a21-c0ffee5eed01";

const BATCHES = [
  { input: "data/ph/directory.json", output: "migrations/directory/0002_seed_ph.sql", seedTime: "2026-10-31T00:00:00.000Z", first: true },
  { input: "data/ph/offices.json", output: "migrations/directory/0003_seed_ph_offices.sql", seedTime: "2026-11-01T00:00:00.000Z" },
];

function uuidv5(name) {
  const ns = Uint8Array.from(NAMESPACE.replace(/-/g, "").match(/../g).map((h) => parseInt(h, 16)));
  const bytes = sha1(new Uint8Array([...ns, ...new TextEncoder().encode(name)])).slice(0, 16);
  bytes[6] = (bytes[6] & 0x0f) | 0x50;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const hex = [...bytes].map((b) => b.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

const q = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

// State shared across batches: places, entities and slugs seen so far.
const geoByKey = new Map();
const entByKey = new Map();
const ids = new Map();
const slugs = new Set();
let geoSort = 0;
let country = null;

function ancestors(geoKey) {
  const out = { region: null, province: null, city: null };
  let cur = geoKey ? geoByKey.get(geoKey) : null;
  for (let i = 0; cur && i < 6; i++) {
    if (cur.type === "REGION") out.region ??= cur.key;
    if (cur.type === "PROVINCE") out.province ??= cur.key;
    if (cur.type === "CITY" || cur.type === "MUNICIPALITY") out.city ??= cur.key;
    cur = cur.parent ? geoByKey.get(cur.parent) : null;
  }
  return out;
}

const depth = (e) => {
  let d = 0;
  for (let cur = e; cur?.parent && d < 10; d++) cur = entByKey.get(cur.parent);
  return d;
};

function uniqueSlug(e) {
  const parent = e.parent ? entByKey.get(e.parent) : null;
  const candidates = [slugify(e.name), parent?.acronym ? slugify(`${e.name} ${parent.acronym}`) : null, slugify(`${e.name} ${e.key}`)];
  for (const c of candidates) if (c && !slugs.has(c)) return slugs.add(c), c;
  throw new Error(`no unique slug for ${e.key}`);
}

for (const batch of BATCHES) {
  const data = JSON.parse(readFileSync(join(root, batch.input), "utf8"));
  country ??= data.country.code;
  const SEED_TIME = batch.seedTime;
  const lines = [
    `-- GENERATED by scripts/build-directory-seed.mjs from ${batch.input}. Do not edit by hand.`,
    "-- Seed listings are unverified: verified_at stays NULL until a curator checks official sources.",
    "",
  ];
  if (batch.first) {
    lines.push(
      `INSERT INTO countries (code, name, path_segment, default_language, status) VALUES (${q(country)}, ${q(data.country.name)}, ${q(data.country.pathSegment)}, ${q(data.country.defaultLanguage)}, 'ACTIVE');`,
      `INSERT INTO countries (code, name, path_segment, default_language, status) VALUES ('SG', 'Singapore', 'sg', 'en', 'PLANNED');`,
      `INSERT INTO countries (code, name, path_segment, default_language, status) VALUES ('US', 'United States', 'us', 'en', 'PLANNED');`,
      "",
    );
  }

  // Geo units (parents first).
  for (const g of data.geo) {
    if (geoByKey.has(g.key)) throw new Error(`duplicate geo key ${g.key}`);
    geoByKey.set(g.key, g);
  }
  const typeOrder = { REGION: 0, PROVINCE: 1, CITY: 2, MUNICIPALITY: 2 };
  const geoSorted = [...data.geo].sort((a, b) => typeOrder[a.type] - typeOrder[b.type]);
  for (const g of geoSorted) {
    lines.push(
      `INSERT INTO geo_units (id, country_code, parent_id, type, official_code, name, short_name, city_class, sort_order) VALUES (${q(g.key)}, ${q(country)}, ${q(g.parent)}, ${q(g.type)}, NULL, ${q(g.name)}, ${q(g.shortName)}, ${q(g.cityClass)}, ${geoSort++});`,
    );
  }
  lines.push("");

  // Entities: parents before children.
  for (const e of data.entities) {
    if (entByKey.has(e.key)) throw new Error(`duplicate entity key ${e.key}`);
    entByKey.set(e.key, e);
    ids.set(e.key, uuidv5(`${country}:entity:${e.key}`));
  }
  const entities = [...data.entities].sort((a, b) => depth(a) - depth(b));

  for (const e of entities) {
    const id = ids.get(e.key);
    if (e.parent && !ids.has(e.parent)) throw new Error(`${e.key}: unknown parent ${e.parent}`);
    if (e.geo && !geoByKey.has(e.geo)) throw new Error(`${e.key}: unknown geo ${e.geo}`);
    const a = ancestors(e.geo);
    const officialIds = JSON.stringify({ seedKey: e.key });
    lines.push(
      `INSERT INTO entities (id, country_code, type, parent_entity_id, geo_unit_id, region_id, province_id, city_id, name, normalized_name, acronym, slug, description, official_url, address, official_ids, status, ratable, verified_at, created_at, updated_at) VALUES (${q(id)}, ${q(country)}, ${q(e.type)}, ${q(e.parent ? ids.get(e.parent) : null)}, ${q(e.geo)}, ${q(a.region)}, ${q(a.province)}, ${q(a.city)}, ${q(e.name)}, ${q(normalizeText(e.name))}, ${q(e.acronym)}, ${q(uniqueSlug(e))}, ${q(e.description)}, ${q(e.officialUrl)}, ${q(e.address)}, ${q(officialIds)}, 'ACTIVE', 1, NULL, ${q(SEED_TIME)}, ${q(SEED_TIME)});`,
    );
    const aliasSet = new Map();
    if (e.acronym) aliasSet.set(normalizeText(e.acronym), [e.acronym, "ACRONYM"]);
    for (const al of e.aliases ?? []) if (!aliasSet.has(normalizeText(al))) aliasSet.set(normalizeText(al), [al, "ALIAS"]);
    for (const al of e.formerNames ?? []) if (!aliasSet.has(normalizeText(al))) aliasSet.set(normalizeText(al), [al, "FORMER_NAME"]);
    for (const [norm, [alias, kind]] of aliasSet) {
      if (!norm) continue;
      lines.push(
        `INSERT INTO entity_aliases (id, entity_id, alias, normalized_alias, kind) VALUES (${q(uuidv5(`${id}:alias:${norm}`))}, ${q(id)}, ${q(alias)}, ${q(norm)}, ${q(kind)});`,
      );
    }
    if (e.officialUrl) {
      lines.push(
        `INSERT INTO entity_sources (id, entity_id, source_url, publisher, checked_at, status, note) VALUES (${q(uuidv5(`${id}:source:official`))}, ${q(id)}, ${q(e.officialUrl)}, 'Official website (seed listing, not yet checked)', NULL, 'UNCHECKED', NULL);`,
      );
    }
    lines.push(
      `INSERT INTO directory_audit (id, action, entity_id, actor_role, actor_ref, case_ref, created_at, change_summary) VALUES (${q(uuidv5(`${id}:audit:seed`))}, 'SEED_IMPORTED', ${q(id)}, 'system', 'seed-builder', NULL, ${q(SEED_TIME)}, ${q(JSON.stringify({ seedKey: e.key, reviewNote: e.reviewNote ?? null }))});`,
    );
  }
  lines.push("");

  // Full-text rows: every entity in the first batch; afterwards only entities not yet indexed.
  lines.push(`INSERT INTO entity_search (entity_id, name, acronym, aliases, place)
SELECT e.id, e.name, COALESCE(e.acronym, ''),
       trim(COALESCE((SELECT group_concat(a.alias, ' ') FROM entity_aliases a WHERE a.entity_id = e.id), '') || ' ' ||
            COALESCE(pe.acronym, '') || ' ' || COALESCE(pe.name, '')),
       trim(COALESCE(g.name, '') || ' ' || COALESCE(c.name, '') || ' ' || COALESCE(pr.name, '') || ' ' ||
            COALESCE(r.name, '') || ' ' || COALESCE(r.short_name, ''))
  FROM entities e
  LEFT JOIN entities pe ON pe.id = e.parent_entity_id
  LEFT JOIN geo_units g ON g.id = e.geo_unit_id
  LEFT JOIN geo_units c ON c.id = e.city_id AND c.id <> e.geo_unit_id
  LEFT JOIN geo_units pr ON pr.id = e.province_id AND pr.id <> e.geo_unit_id
  LEFT JOIN geo_units r ON r.id = e.region_id AND r.id <> e.geo_unit_id
 WHERE e.country_code = ${q(country)}${batch.first ? "" : "\n   AND e.id NOT IN (SELECT entity_id FROM entity_search)"};`);

  writeFileSync(join(root, batch.output), lines.join("\n") + "\n");
  console.log(`${batch.output}: ${data.geo.length} geo units, ${data.entities.length} entities`);
}
